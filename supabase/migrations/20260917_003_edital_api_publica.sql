-- 2. Informação clínica (H.D., medicação em uso) separada da identificação
-- ---------------------------------------------------------------------
create table if not exists public.patient_clinical_info (
  patient_id uuid primary key references public.patients(id),
  diagnostic_hypothesis text,
  medications text,
  updated_by uuid references public.profiles(id),
  updated_at timestamptz not null default now()
);
alter table public.patient_clinical_info enable row level security;
drop policy if exists clinical_info_select on public.patient_clinical_info;
create policy clinical_info_select on public.patient_clinical_info for select to authenticated
  using ((select public.is_clinical()));
grant select on public.patient_clinical_info to authenticated;

drop trigger if exists trg_block_delete on public.patient_clinical_info;
create trigger trg_block_delete before delete on public.patient_clinical_info
  for each row execute function cuidar_private.tg_block_delete();
drop trigger if exists trg_audit on public.patient_clinical_info;
create trigger trg_audit after insert or update on public.patient_clinical_info
  for each row execute function cuidar_private.tg_audit();

create or replace function cuidar_private.tg_clinical_revision() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_version int;
begin
  if to_jsonb(old) - 'updated_at' = to_jsonb(new) - 'updated_at' then return null; end if;
  select coalesce(max(version), 0) + 1 into v_version
  from public.record_revisions where table_name = 'patient_clinical_info' and record_id = old.patient_id;
  insert into public.record_revisions (table_name, record_id, version, changed_fields, old_data, new_data, changed_by)
  values ('patient_clinical_info', old.patient_id, v_version, array['diagnostic_hypothesis', 'medications'], to_jsonb(old), to_jsonb(new), auth.uid());
  return null;
end $$;
drop trigger if exists trg_revision on public.patient_clinical_info;
create trigger trg_revision after update on public.patient_clinical_info
  for each row execute function cuidar_private.tg_clinical_revision();

create or replace function public.save_clinical_info(p_patient uuid, p_hypothesis text, p_medications text)
returns void
language plpgsql security definer set search_path = public as $$
begin
  perform public.assert_role('profissional','coordenacao','admin');
  insert into public.patient_clinical_info (patient_id, diagnostic_hypothesis, medications, updated_by, updated_at)
  values (p_patient, nullif(btrim(p_hypothesis), ''), nullif(btrim(p_medications), ''), auth.uid(), now())
  on conflict (patient_id) do update
    set diagnostic_hypothesis = excluded.diagnostic_hypothesis, medications = excluded.medications,
        updated_by = excluded.updated_by, updated_at = now();
end $$;
revoke all on function public.save_clinical_info(uuid, text, text) from public, anon;
grant execute on function public.save_clinical_info(uuid, text, text) to authenticated;

