create table if not exists public.agent_knowledge (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  content text not null,
  service text,
  audience text not null default 'publico',
  published boolean not null default false,
  updated_at timestamptz not null default now()
);
alter table public.agent_knowledge enable row level security;
drop policy if exists agent_knowledge_admin on public.agent_knowledge;
create policy agent_knowledge_admin on public.agent_knowledge for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists agent_knowledge_read on public.agent_knowledge;
create policy agent_knowledge_read on public.agent_knowledge for select to authenticated using (published or (select public.is_admin()));
grant select, insert, update on public.agent_knowledge to authenticated;

create index if not exists agent_knowledge_search_idx
  on public.agent_knowledge using gin (
    to_tsvector('portuguese', coalesce(title, '') || ' ' || coalesce(content, '') || ' ' || coalesce(service, ''))
  );

create or replace function public.search_agent_knowledge(search_query text, result_limit integer default 5)
returns table (title text, content text, service text, audience text, updated_at timestamptz)
language sql stable set search_path = public, extensions
as $$
  with q as (select websearch_to_tsquery('portuguese', left(coalesce(search_query, ''), 500)) as tsq,
                    public.f_norm(search_query) as norm)
  select k.title, k.content, k.service, k.audience, k.updated_at
  from public.agent_knowledge k, q
  where k.published = true
    and (to_tsvector('portuguese', coalesce(k.title, '') || ' ' || coalesce(k.content, '') || ' ' || coalesce(k.service, '')) @@ q.tsq
         or public.f_norm(k.title || ' ' || coalesce(k.service, '')) % q.norm)
  order by ts_rank(to_tsvector('portuguese', coalesce(k.title, '') || ' ' || coalesce(k.content, '') || ' ' || coalesce(k.service, '')), q.tsq) desc,
           k.updated_at desc
  limit least(greatest(result_limit, 1), 8);
$$;
revoke all on function public.search_agent_knowledge(text, integer) from public, anon, authenticated;
grant execute on function public.search_agent_knowledge(text, integer) to service_role;

