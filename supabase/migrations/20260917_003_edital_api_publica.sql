-- 5. Visão pública da rede (somente agregados, sem dado pessoal)
-- ---------------------------------------------------------------------
create or replace function public.public_network_overview()
returns jsonb
language sql stable security definer set search_path = public
as $$
  select jsonb_build_object(
    'atualizado_em', now(),
    'aviso', 'Dados agregados e fictícios para demonstração. Não contém informação individual.',
    'servicos', coalesce((
      select jsonb_agg(jsonb_build_object(
        'codigo', s.code, 'nome', s.name, 'descricao', s.description, 'secretaria', s.secretaria,
        'endereco', s.address, 'telefone', s.phone,
        'especialidades', coalesce((
          select jsonb_agg(jsonb_build_object(
            'nome', sp.name,
            'vagas_mes', ss.monthly_capacity,
            -- faixas em vez de números exatos quando a fila é pequena (evita reidentificação)
            'pessoas_aguardando', case when w.waiting < 5 then 'menos de 5' else w.waiting::text end,
            'espera_mediana_dias', case when w.waiting < 5 then null else w.median_wait end
          ) order by sp.name)
          from public.service_specialties ss
          join public.specialties sp on sp.id = ss.specialty_id
          left join lateral (
            select count(*) as waiting,
                   round((percentile_cont(0.5) within group (order by extract(epoch from now() - q.entered_at) / 86400))::numeric, 0) as median_wait
            from public.queue_entries q
            where q.service_id = ss.service_id and q.specialty_id = ss.specialty_id and q.status = 'aguardando'
          ) w on true
          where ss.service_id = s.id and ss.active
        ), '[]'::jsonb)
      ) order by s.name)
      from public.services s where s.active
    ), '[]'::jsonb),
    'rede', jsonb_build_object(
      'pessoas_acompanhadas', (select count(distinct patient_id) from public.queue_entries where status = 'em_atendimento'),
      'atendimentos_ultimos_30_dias', (select count(*) from public.appointments where status = 'presente' and scheduled_for >= now() - interval '30 days' and scheduled_for <= now()),
      'taxa_comparecimento_30_dias', (select round(100.0 * count(*) filter (where status = 'presente')
                                        / nullif(count(*) filter (where status in ('presente','falta_justificada','falta_injustificada')), 0), 0)
                                      from public.appointments where scheduled_for >= now() - interval '30 days' and scheduled_for <= now()),
      'encaminhamentos_respondidos_30_dias', (select count(*) from public.referrals where responded_at >= now() - interval '30 days')
    )
  )
$$;
revoke all on function public.public_network_overview() from public, anon, authenticated;
grant execute on function public.public_network_overview() to service_role;

